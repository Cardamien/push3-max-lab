#!/usr/bin/env python3
"""Write face/VirtualPush.maxpat: the v8ui face (which also draws the screen from the named matrix
fed by jit.net.recv), the UDP links to pushbridge, an MPE toggle and a console readout.
Run from anywhere: python3 face/build-patcher.py"""
import json, pathlib
here = pathlib.Path(__file__).resolve().parent
W = 1000; S = W / 2000; H = round(1668 * S)
sx, sy, sw, sh = 388, 322, 1216, 202                     # screen slot in layout units
screen = [round(sx * S), round(sy * S), round(sw * S), round(sh * S)]
def box(id, maxclass, text, x, y, w, h, **extra):
    b = {"id": id, "maxclass": maxclass, "patching_rect": [x, y, w, h], "numinlets": 1, "numoutlets": 1, "outlettype": [""]}
    if text is not None: b["text"] = text
    b.update(extra); return {"box": b}
boxes = [
    box("face", "v8ui", None, 0, 0, W, H, filename="vpush.js", numinlets=1, numoutlets=2, outlettype=["", ""], varname="face"),
    box("recv", "newobj", "jit.net.recv @port 7474", 20, H + 20, 150, 22, numoutlets=2, outlettype=["jit_matrix", ""], varname="screen_recv"),
    box("mtx", "newobj", "jit.matrix 4 char 960 160 @name vpush_screen", 20, H + 50, 260, 22, numoutlets=2, outlettype=["jit_matrix", ""], varname="screen_mtx"),
    box("udpin", "newobj", "udpreceive 7476", 300, H + 20, 110, 22),
    box("udpout", "newobj", "udpsend 127.0.0.1 7475", 300, H + 80, 150, 22, numoutlets=0, outlettype=[]),
    box("mpet", "toggle", None, 480, H + 20, 20, 20, numoutlets=1, outlettype=["int"], varname="mpe_toggle"),
    box("mpemsg", "message", "mpe $1", 505, H + 20, 50, 22, numinlets=2),
    box("mpec", "comment", "MPE pads (each pad on its own channel 2-16): only if MPE is enabled in the Push Setup; off = pads on channel 1, what Live expects by default", 560, H + 20, 420, 20, numinlets=0, numoutlets=0, outlettype=[]),
    box("lb", "newobj", "loadbang", 480, H + 50, 60, 22, numoutlets=1, outlettype=["bang"]),
    box("one", "message", "0", 480, H + 80, 25, 22, numinlets=2),
    box("con", "comment", "console (last event)", 600, H + 50, 140, 20, numinlets=0, numoutlets=0, outlettype=[]),
    box("conm", "message", None, 600, H + 80, 380, 22, numinlets=2),
    box("help", "comment", "Virtual Push 3: start run.sh first (pushbridge, Live, the fake Push helper). See face/README.md.", 20, H + 110, 700, 20, numinlets=0, numoutlets=0, outlettype=[]),
]
lines = [("recv", 0, "mtx", 0), ("mtx", 0, "face", 0), ("udpin", 0, "face", 0), ("face", 0, "udpout", 0), ("face", 1, "conm", 1),
         ("mpet", 0, "mpemsg", 0), ("mpemsg", 0, "face", 0), ("lb", 0, "one", 0), ("one", 0, "mpet", 0)]
patcher = {"patcher": {"fileversion": 1, "appversion": {"major": 9, "minor": 0, "revision": 0, "architecture": "x64", "modernui": 1},
    "classnamespace": "box", "rect": [80.0, 80.0, W + 40.0, H + 150.0], "title": "Virtual Push 3", "bglocked": 0, "openinpresentation": 0,
    "boxes": boxes, "lines": [{"patchline": {"source": [a, o], "destination": [b, i]}} for a, o, b, i in lines]}}
pal = json.load(open(here.parent / "data/push3-palette.json"))["palette"]
(here / "palette.js").write_text("// Live's LED colour palette as read from a Push 3 (data/push3-palette.json); index -> [r, g, b, w] 0..255.\n// Generated by face/build-patcher.py; do not edit by hand.\nconst PALETTE = " + json.dumps(pal, separators=(",", ":")) + ";\nif (typeof exports !== 'undefined') exports.PALETTE = PALETTE;\n")
out = here / "VirtualPush.maxpat"; out.write_text(json.dumps(patcher, indent=1)); print(out, "screen at", screen)
